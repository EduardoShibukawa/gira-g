// Package skills holds GIRA's skills catalog (spec A): one canonical SKILL.md per
// skill, embedded in the binary, and `gira skills install`, which generates the
// files each host family reads from that single source. The installer only ever
// rewrites content between its own markers, so a second run changes nothing and
// anything a user added outside the markers survives.
package skills

import (
	"bytes"
	"embed"
	"fmt"
	"io/fs"
	"path"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

//go:embed catalog/*/SKILL.md
var catalog embed.FS

// Skill is one canonical skill source.
type Skill struct {
	Name           string   `yaml:"name"`
	Description    string   `yaml:"description"`
	Operations     []string `yaml:"operations"`
	OutputContract string   `yaml:"output_contract"`
	Budget         any      `yaml:"budget"`
	// Frontmatter and Body are the two halves of the source file.
	Frontmatter string `yaml:"-"`
	Body        string `yaml:"-"`
}

// Catalog returns every canonical skill, sorted by name.
func Catalog() ([]Skill, error) {
	dirs, err := fs.ReadDir(catalog, "catalog")
	if err != nil {
		return nil, err
	}
	var out []Skill
	for _, d := range dirs {
		data, err := catalog.ReadFile(path.Join("catalog", d.Name(), "SKILL.md"))
		if err != nil {
			return nil, err
		}
		s, err := Parse(data)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", d.Name(), err)
		}
		if s.Name != d.Name() {
			return nil, fmt.Errorf("%s: name %q does not match its directory", d.Name(), s.Name)
		}
		out = append(out, s)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, nil
}

// Parse reads a SKILL.md and checks the fields every skill must declare: a trigger
// description, the operations it uses, its output contract and its budget.
// CRLF line endings are normalized so files checked out or edited on Windows
// parse the same as on LF platforms.
func Parse(data []byte) (Skill, error) {
	text := strings.ReplaceAll(string(data), "\r\n", "\n")
	if !strings.HasPrefix(text, "---\n") {
		return Skill{}, fmt.Errorf("missing frontmatter")
	}
	end := strings.Index(text[4:], "\n---\n")
	if end < 0 {
		return Skill{}, fmt.Errorf("unterminated frontmatter")
	}
	front := text[4 : 4+end+1]
	var s Skill
	if err := yaml.Unmarshal([]byte(front), &s); err != nil {
		return Skill{}, fmt.Errorf("frontmatter: %w", err)
	}
	s.Frontmatter = front
	s.Body = text[4+end+5:]
	var missing []string
	if s.Name == "" {
		missing = append(missing, "name")
	}
	if s.Description == "" {
		missing = append(missing, "description")
	}
	if len(s.Operations) == 0 {
		missing = append(missing, "operations")
	}
	if s.OutputContract == "" {
		missing = append(missing, "output_contract")
	}
	if s.Budget == nil {
		missing = append(missing, "budget")
	}
	for _, sec := range []string{"## Operations", "## Output contract", "## Budget"} {
		if !strings.Contains(s.Body, sec) {
			missing = append(missing, sec)
		}
	}
	if len(missing) > 0 {
		return Skill{}, fmt.Errorf("missing %s", strings.Join(missing, ", "))
	}
	return s, nil
}

// Markers delimit what the installer owns inside a file. Begin and end lines
// contain these tokens followed by a region id, in whatever comment syntax the
// file uses.
const (
	beginToken = "gira:begin "
	endToken   = "gira:end "
)

// region is one owned block: its id, the comment syntax of its marker lines, and
// its content (without the marker lines).
type region struct {
	id, open, close, content string
}

func (r region) render() string {
	return fmt.Sprintf("%s%s%s (generated by `gira skills install`; edits inside are overwritten)%s\n%s%s%s%s%s\n",
		r.open, beginToken, r.id, r.close, r.content, r.open, endToken, r.id, r.close)
}

// applyRegions replaces each region's content in existing, between its markers.
// A region whose markers are missing is appended at the end; when existing is
// empty, skeleton lays the regions out instead. Everything outside the markers is
// kept byte for byte.
func applyRegions(existing []byte, skeleton func() string, regions []region) ([]byte, error) {
	if len(existing) == 0 {
		return []byte(skeleton()), nil
	}
	text := string(existing)
	for _, r := range regions {
		lines := strings.SplitAfter(text, "\n")
		begin, end := -1, -1
		for i, l := range lines {
			if strings.Contains(l, beginToken+r.id+" ") || strings.HasSuffix(strings.TrimRight(l, "\n"), beginToken+r.id) {
				if begin >= 0 {
					return nil, fmt.Errorf("duplicate begin marker for region %q", r.id)
				}
				begin = i
			}
			if strings.Contains(l, endToken+r.id) && begin >= 0 && end < 0 && i > begin {
				end = i
			}
		}
		switch {
		case begin < 0:
			if !strings.HasSuffix(text, "\n") {
				text += "\n"
			}
			text += r.render()
		case end < 0:
			return nil, fmt.Errorf("region %q has a begin marker but no end marker", r.id)
		default:
			var b bytes.Buffer
			for _, l := range lines[:begin] {
				b.WriteString(l)
			}
			b.WriteString(r.render())
			for _, l := range lines[end+1:] {
				b.WriteString(l)
			}
			text = b.String()
		}
	}
	return []byte(text), nil
}
